// Production (and dev) build: bundles src/ with esbuild, writes index.html,
// the web app manifest and a precaching service worker into dist/.
//
//   node scripts/build.mjs                      -> dist/, base "/"
//   node scripts/build.mjs --base=/pocket-ledger/ -> dist/, base "/pocket-ledger/"
import { build as esbuild } from "esbuild";
import { createHash } from "node:crypto";
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { readBase } from "./base.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const APP = {
  name: "Pocket Ledger",
  shortName: "Ledger",
  description: "Track income, expenses, savings and goals. Private: your data stays on this device.",
  themeLight: "#f3f5f4",
  themeDark: "#0f1513",
};

/**
 * @param {{ base?: string, dev?: boolean, outdir?: string, quiet?: boolean }} [options]
 * @returns {Promise<{ outdir: string, base: string, version: string, files: string[] }>}
 */
export async function build({ base = "/", dev = false, outdir = path.join(ROOT, "dist"), quiet = false } = {}) {
  await rm(outdir, { recursive: true, force: true });
  await mkdir(path.join(outdir, "assets"), { recursive: true });

  const result = await esbuild({
    entryPoints: { app: path.join(ROOT, "src/main.ts") },
    bundle: true,
    format: "esm",
    target: ["es2020", "safari16", "chrome110", "firefox110"],
    minify: !dev,
    sourcemap: dev ? "inline" : false,
    outdir: path.join(outdir, "assets"),
    entryNames: dev ? "[name]" : "[name]-[hash]",
    assetNames: dev ? "[name]" : "[name]-[hash]",
    metafile: true,
    legalComments: "none",
    logLevel: "silent",
    define: {
      __BASE__: JSON.stringify(base),
      __DEV__: JSON.stringify(dev),
    },
  });

  const outputs = Object.keys(result.metafile.outputs).map((p) => path.relative(outdir, path.resolve(p)).split(path.sep).join("/"));
  const js = outputs.find((p) => p.endsWith(".js"));
  const css = outputs.find((p) => p.endsWith(".css"));
  if (!js || !css) throw new Error("Build produced no JS or CSS bundle");

  const publicDir = path.join(ROOT, "public");
  if (existsSync(publicDir)) await cp(publicDir, outdir, { recursive: true });

  const template = await readFile(path.join(ROOT, "src/index.html"), "utf8");
  const html = template
    .replaceAll("%BASE%", base)
    .replaceAll("%CSS%", base + css)
    .replaceAll("%JS%", base + js)
    .replaceAll("%NAME%", APP.name)
    .replaceAll("%DESCRIPTION%", APP.description)
    .replaceAll("%THEME_LIGHT%", APP.themeLight)
    .replaceAll("%THEME_DARK%", APP.themeDark);
  await writeFile(path.join(outdir, "index.html"), html);

  const manifest = {
    name: APP.name,
    short_name: APP.shortName,
    description: APP.description,
    id: base,
    start_url: base,
    scope: base,
    display: "standalone",
    orientation: "portrait",
    background_color: APP.themeLight,
    theme_color: APP.themeLight,
    lang: "en",
    icons: [
      { src: base + "icons/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any" },
      { src: base + "icons/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any" },
      { src: base + "icons/icon-maskable-512.png", sizes: "512x512", type: "image/png", purpose: "maskable" },
    ],
  };
  await writeFile(path.join(outdir, "manifest.webmanifest"), JSON.stringify(manifest, null, 2));

  const files = (await listFiles(outdir)).sort();
  const hash = createHash("sha256");
  for (const f of files) {
    hash.update(f);
    hash.update(await readFile(path.join(outdir, f)));
  }
  const version = hash.digest("hex").slice(0, 12);

  if (!dev) {
    const precache = files.map((f) => base + f);
    await writeFile(path.join(outdir, "sw.js"), serviceWorker({ base, version, precache }));
  }
  await writeFile(path.join(outdir, "build-info.json"), JSON.stringify({ base, version, dev }, null, 2));

  if (!quiet) console.log(`Built ${dev ? "dev" : "production"} app at base ${base} (version ${version}) -> ${path.relative(ROOT, outdir) || "."}`);
  return { outdir, base, version, files };
}

async function listFiles(dir, prefix = "") {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const rel = prefix + entry.name;
    if (entry.isDirectory()) out.push(...(await listFiles(path.join(dir, entry.name), rel + "/")));
    else if (rel !== "sw.js" && rel !== "build-info.json") out.push(rel);
  }
  return out;
}

/** The service worker: precache everything, serve offline, and never activate an update on its own. */
function serviceWorker({ base, version, precache }) {
  return `// Generated by scripts/build.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(base)};
const CACHE = "pocket-ledger-" + VERSION;
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  // No skipWaiting(): an update waits until the owner chooses "Reload now" or closes the app.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k.startsWith("pocket-ledger-") && k !== CACHE).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
  if (event.data && event.data.type === "GET_VERSION" && event.source) event.source.postMessage({ type: "VERSION", version: VERSION });
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return;
  if (request.mode === "navigate") {
    event.respondWith(caches.match(BASE + "index.html", { cacheName: CACHE }).then((hit) => hit || fetch(request)));
    return;
  }
  event.respondWith(caches.match(request, { cacheName: CACHE }).then((hit) => hit || fetch(request)));
});
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  build({ base: readBase() }).catch((err) => {
    console.error(err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
